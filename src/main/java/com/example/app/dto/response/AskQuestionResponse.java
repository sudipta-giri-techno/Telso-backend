package com.example.app.dto.response;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;
import java.util.List;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Response returned by Gemini AI to the Content Admin")
public class AskQuestionResponse {

    @Schema(description = "The answer generated by Gemini AI",
            example = "Photosynthesis is the process by which green plants use sunlight, water, and carbon dioxide to make food.")
    private String answer;

    @Schema(description = "Estimated confidence score formatted as string or percentage", example = "98%")
    private String confidenceScore;

    @Schema(description = "List of relevant source references (titles/chapters) matched from content library if applicable")
    private List<SourceReference> sources;

    @Schema(description = "Name of the Gemini model used", example = "gemini-1.5-flash")
    private String modelUsed;

    @Schema(description = "Timestamp when the answer was generated")
    private LocalDateTime timestamp;

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class SourceReference {
        private Long contentId;
        private String title;
        private String subject;
        private String targetClass;
        private String chapter;
        private String topic;
    }
}

